// Orbitwerk - OrbitwerkCore
// UE-Modul fuer Vessel, Parts, Staging und die Physik-Bruecke zu OrbitCore.
//
// OrbitCore (space-game/ThirdParty/OrbitCore) ist reines C++17 ohne UE-Abhaengigkeit und
// wird parallel gebaut (Task T10). Dieses Build.cs verdrahtet es automatisch, sobald es existiert:
//   * ThirdParty/OrbitCore/include            -> PublicIncludePaths (auch fuer abhaengige Module)
//   * ThirdParty/OrbitCore/{third_party,external,extern,vendor}[/include] -> PublicIncludePaths
//   * ThirdParty/OrbitCore/src/**/*.cpp|.cc   -> je eine Wrapper-.cpp unter Private/OrbitCoreSources/
//     (automatisch erzeugt, git-ignoriert), damit UBT die Quellen mitkompiliert.
//   * WITH_ORBITCORE=1 (sonst 0) als Public-Define.
//
// Abschalten (z. B. wenn OrbitCore gerade nicht kompiliert): Umgebungsvariable
//   ORBITWERK_DISABLE_ORBITCORE=1
//
// Wichtig: Dieses Modul nutzt KEINE PCH und KEINEN Unity-Build. So landen in den OrbitCore-
// Uebersetzungseinheiten keine UE-Makros (PI, check, verify, ...), und jede OrbitCore-.cpp
// bleibt eine eigene Uebersetzungseinheit (keine Kollisionen von static/anonymous-namespace-Symbolen).

using System;
using System.Collections.Generic;
using System.IO;
using UnrealBuildTool;

public class OrbitwerkCore : ModuleRules
{
	private const string GeneratedPrefix = "OC_";

	public OrbitwerkCore(ReadOnlyTargetRules Target) : base(Target)
	{
		PCHUsage = PCHUsageMode.NoPCHs;
		bUseUnity = false;

		PublicDependencyModuleNames.AddRange(new string[]
		{
			"Core",
			"CoreUObject",
			"Engine"
		});

		ConfigureOrbitCore();
	}

	private string OrbitCoreRoot
	{
		get { return Path.GetFullPath(Path.Combine(ModuleDirectory, "..", "..", "ThirdParty", "OrbitCore")); }
	}

	private string GeneratedSourceDir
	{
		get { return Path.Combine(ModuleDirectory, "Private", "OrbitCoreSources"); }
	}

	private void ConfigureOrbitCore()
	{
		string IncludeDir = Path.Combine(OrbitCoreRoot, "include");
		bool bDisabled = Environment.GetEnvironmentVariable("ORBITWERK_DISABLE_ORBITCORE") == "1";

		if (bDisabled || !Directory.Exists(IncludeDir))
		{
			PublicDefinitions.Add("WITH_ORBITCORE=0");
			SyncGeneratedSources(new List<string>(), string.Empty);
			return;
		}

		PublicDefinitions.Add("WITH_ORBITCORE=1");
		PublicIncludePaths.Add(IncludeDir);

		// Optionale, mitgelieferte Header-only-Abhaengigkeiten (z. B. nlohmann/json).
		foreach (string ExtraName in new string[] { "third_party", "thirdparty", "external", "extern", "vendor" })
		{
			string ExtraDir = Path.Combine(OrbitCoreRoot, ExtraName);
			if (Directory.Exists(ExtraDir))
			{
				PublicIncludePaths.Add(ExtraDir);
				string ExtraInclude = Path.Combine(ExtraDir, "include");
				if (Directory.Exists(ExtraInclude))
				{
					PublicIncludePaths.Add(ExtraInclude);
				}
			}
		}

		// OrbitCore ist Standard-C++ (std::optional, nlohmann::json, ...) und darf Exceptions nutzen.
		bEnableExceptions = true;

		// Aenderungen an der CMake-Datei (neue Quelldateien) sollen UBT zum Neueinlesen bringen.
		string CMakeLists = Path.Combine(OrbitCoreRoot, "CMakeLists.txt");
		if (File.Exists(CMakeLists))
		{
			ExternalDependencies.Add(CMakeLists);
		}

		string SrcDir = Path.Combine(OrbitCoreRoot, "src");
		List<string> Sources = new List<string>();
		if (Directory.Exists(SrcDir))
		{
			foreach (string FilePath in Directory.GetFiles(SrcDir, "*.*", SearchOption.AllDirectories))
			{
				string Extension = Path.GetExtension(FilePath).ToLowerInvariant();
				string FileName = Path.GetFileName(FilePath).ToLowerInvariant();
				if ((Extension == ".cpp" || Extension == ".cc") && FileName != "main.cpp")
				{
					Sources.Add(FilePath);
				}
			}
			Sources.Sort(StringComparer.OrdinalIgnoreCase);
		}

		SyncGeneratedSources(Sources, SrcDir);
	}

	/// Erzeugt pro OrbitCore-Quelldatei eine kleine Wrapper-.cpp im Modul und entfernt veraltete Wrapper.
	private void SyncGeneratedSources(List<string> Sources, string SrcDir)
	{
		HashSet<string> Expected = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

		if (Sources.Count > 0)
		{
			Directory.CreateDirectory(GeneratedSourceDir);
		}

		foreach (string Source in Sources)
		{
			string Relative = Path.GetRelativePath(SrcDir, Source);
			string SafeName = GeneratedPrefix + Relative.Replace('\\', '_').Replace('/', '_').Replace('.', '_').Replace(' ', '_') + ".cpp";
			string WrapperPath = Path.Combine(GeneratedSourceDir, SafeName);
			string IncludePath = Path.GetRelativePath(GeneratedSourceDir, Source).Replace('\\', '/');

			string Content =
				"// AUTO-GENERATED by OrbitwerkCore.Build.cs - do not edit, do not commit.\n" +
				"// Compiles ThirdParty/OrbitCore/src/" + Relative.Replace('\\', '/') + " as part of the OrbitwerkCore module.\n" +
				"#include \"HAL/Platform.h\"\n" +
				"THIRD_PARTY_INCLUDES_START\n" +
				"#include \"" + IncludePath + "\"\n" +
				"THIRD_PARTY_INCLUDES_END\n";

			WriteIfChanged(WrapperPath, Content);
			Expected.Add(Path.GetFullPath(WrapperPath));
		}

		if (!Directory.Exists(GeneratedSourceDir))
		{
			return;
		}

		foreach (string Existing in Directory.GetFiles(GeneratedSourceDir, GeneratedPrefix + "*.cpp"))
		{
			if (!Expected.Contains(Path.GetFullPath(Existing)))
			{
				File.Delete(Existing);
			}
		}

		if (Directory.GetFileSystemEntries(GeneratedSourceDir).Length == 0)
		{
			Directory.Delete(GeneratedSourceDir);
		}
	}

	private static void WriteIfChanged(string FilePath, string Content)
	{
		if (File.Exists(FilePath) && File.ReadAllText(FilePath) == Content)
		{
			return;
		}
		File.WriteAllText(FilePath, Content);
	}
}
